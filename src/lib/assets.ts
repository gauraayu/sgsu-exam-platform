import "server-only";
import fs from "node:fs";
import path from "node:path";
import { SUBJECT_SLUGS, SUBJECTS } from "./constants";

let cache: { at: number; files: Set<string> } | null = null;
const TTL_MS = 30_000;

function scanPublicFolder(): Set<string> | null {
  const root = path.join(process.cwd(), "public", "questions");
  if (!fs.existsSync(root)) return null;
  const files = new Set<string>();
  for (const subject of SUBJECTS) {
    const slug = SUBJECT_SLUGS[subject];
    const dir = path.join(root, slug, "images");
    if (!fs.existsSync(dir)) continue;
    for (const f of fs.readdirSync(dir)) files.add(`/questions/${slug}/images/${f}`);
  }
  return files;
}

function readManifest(): Set<string> {
  const file = path.join(process.cwd(), "src", "data", "asset-manifest.json");
  try {
    const list = JSON.parse(fs.readFileSync(file, "utf8")) as { files: string[] };
    return new Set(list.files);
  } catch {
    return new Set();
  }
}

/**
 * Set of browser paths of question images that exist. In development the public folder is
 * scanned directly; on serverless platforms (where public/ is served by the CDN and is not on
 * the function filesystem) the build-time manifest generated by scripts/generate-asset-manifest.ts is used.
 */
export function getAvailableImages(): Set<string> {
  if (cache && Date.now() - cache.at < TTL_MS) return cache.files;
  const files = scanPublicFolder() ?? readManifest();
  cache = { at: Date.now(), files };
  return files;
}

export function imageExists(browserPath: string): boolean {
  return getAvailableImages().has(browserPath);
}
